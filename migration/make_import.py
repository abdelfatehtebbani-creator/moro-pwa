"""Builds server/ImportData.gs from migration/out/*.csv (run after migrate_v13.py).
The generated file holds business data: it is git-ignored and removed from the
Apps Script project right after the one-time import."""
import csv, json, os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, 'out')
DEST = os.path.join(HERE, '..', 'server', 'ImportData.gs')
NUMERIC = {'qty', 'price', 'amount', 'discount', 'final_amount', 'min_stock', 'qty_per_unit'}
BOOL = {'active'}
ORDER = ['Settings', 'Items', 'Parties', 'Locations', 'Purposes', 'Recipes', 'Lists', 'Contacts', 'Reminders',
         'Balances', 'Movements', 'Archive']

data = {}
for name in ORDER:
    with open(os.path.join(OUT, name + '.csv'), encoding='utf-8-sig', newline='') as f:
        rows = list(csv.reader(f))
    head, body = rows[0], rows[1:]
    conv = []
    for r in body:
        row = []
        for h, v in zip(head, r):
            if h in NUMERIC and v != '':
                fv = float(v)
                row.append(int(fv) if fv == int(fv) else fv)
            elif h in BOOL:
                row.append(v.upper() == 'TRUE')
            else:
                row.append(v)
        conv.append(row)
    if conv:
        data[name] = conv

with open(DEST, 'w', encoding='utf-8') as f:
    f.write('// GENERATED by migration/make_import.py – business data, never commit. Delete after import.\n')
    f.write('var IMPORT_DATA = ')
    json.dump(data, f, ensure_ascii=False, separators=(',', ':'))
    f.write(';\n')
print({k: len(v) for k, v in data.items()}, os.path.getsize(DEST), 'bytes')
